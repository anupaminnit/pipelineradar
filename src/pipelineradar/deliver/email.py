"""Email delivery for intelligence briefs.

send_brief() is the single public entry point. It reads SMTP config from
environment variables and degrades gracefully to a file write if any required
variable is absent — the graph must never abort due to a missing email config.

Env vars consumed (all optional — absence triggers file fallback):
  SMTP_HOST, SMTP_PORT (default 587), SMTP_USER, SMTP_PASSWORD, ALERT_TO_EMAIL
"""

from __future__ import annotations

import asyncio
import os
import re
import smtplib
from email import encoders
from email.mime.base import MIMEBase
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from pathlib import Path

import structlog

from pipelineradar.schemas import GroundedBrief

log: structlog.stdlib.BoundLogger = structlog.get_logger(__name__)

_OUTPUT_DIR = Path("output")


async def send_brief(grounded: GroundedBrief, markdown: str, run_id: str) -> None:
    """Send the brief by email, writing to output/ if SMTP is not configured."""
    smtp_host: str | None = os.environ.get("SMTP_HOST")
    smtp_port_str: str = os.environ.get("SMTP_PORT", "587")
    smtp_user: str | None = os.environ.get("SMTP_USER")
    smtp_password: str | None = os.environ.get("SMTP_PASSWORD")
    alert_to: str | None = os.environ.get("ALERT_TO_EMAIL")

    n_items = _count_cited_items(grounded)
    date_str = grounded.generated_at.strftime("%Y-%m-%d")
    subject = (
        f"PipelineRadar · {grounded.therapeutic_area}"
        f" · {n_items} new items · {date_str}"
    )

    if not (smtp_host and smtp_user and smtp_password and alert_to):
        log.warning(
            "email.smtp_not_configured",
            run_id=run_id,
            missing=[
                k
                for k, v in {
                    "SMTP_HOST": smtp_host,
                    "SMTP_USER": smtp_user,
                    "SMTP_PASSWORD": smtp_password,
                    "ALERT_TO_EMAIL": alert_to,
                }.items()
                if not v
            ],
        )
        _write_fallback(markdown, grounded.therapeutic_area, run_id)
        return

    html_body = _build_html(grounded, markdown)

    msg = MIMEMultipart("mixed")
    msg["Subject"] = subject
    msg["From"] = smtp_user
    msg["To"] = alert_to

    msg.attach(MIMEText(html_body, "html", "utf-8"))

    ta_slug = grounded.therapeutic_area.replace(" ", "_").lower()
    attach_name = f"brief_{ta_slug}_{run_id}.md"
    attachment = MIMEBase("application", "octet-stream")
    attachment.set_payload(markdown.encode("utf-8"))
    encoders.encode_base64(attachment)
    attachment.add_header("Content-Disposition", "attachment", filename=attach_name)
    msg.attach(attachment)

    try:
        smtp_port = int(smtp_port_str)
        await asyncio.to_thread(
            _smtp_send, smtp_host, smtp_port, smtp_user, smtp_password, alert_to, msg
        )
        log.info("email.sent", run_id=run_id, to=alert_to, subject=subject)
    except Exception as exc:
        log.error("email.send_failed", run_id=run_id, error=str(exc))
        _write_fallback(markdown, grounded.therapeutic_area, run_id)


